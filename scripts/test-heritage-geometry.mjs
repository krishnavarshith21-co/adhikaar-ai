import fs from 'node:fs/promises';
import ts from 'typescript';
import * as THREE from 'three';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('..',import.meta.url)).replace(/\/$/,'');
await fs.mkdir(root+'/.qa-artifacts',{recursive:true});
const source=await fs.readFile(root+'/src/components/three/heritage-model.ts','utf8');
await fs.writeFile(root+'/.qa-artifacts/heritage-model.mjs',ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {createHeritageModel}=await import(root+'/.qa-artifacts/heritage-model.mjs');
const model=createHeritageModel();model.group.updateMatrixWorld(true);
const bounds=new THREE.Box3().setFromObject(model.group),triangles=model.group.children.reduce((n,m)=>n+m.geometry.attributes.position.count/3,0);
assert.equal(model.group.children.length,6);assert.ok(triangles<350000);assert.ok(bounds.max.y<4.7);assert.ok(bounds.min.y>-.03);
const ray=new THREE.Raycaster(new THREE.Vector3(0,1.1,10),new THREE.Vector3(0,0,-1));
assert.equal(ray.intersectObject(model.group,true).length,0,'central arch must remain open through the pavilion');
ray.set(new THREE.Vector3(1.28,1.1,10),new THREE.Vector3(0,0,-1));assert.ok(ray.intersectObject(model.group,true).length>0,'corner pier must have volume');
model.group.children.forEach(m=>assert.ok(m.geometry.attributes.position.array.every(Number.isFinite)));
let geometryDisposals=0,materialDisposals=0;model.group.children.forEach(m=>{m.geometry.addEventListener('dispose',()=>geometryDisposals++);m.material.addEventListener('dispose',()=>materialDisposals++);});model.dispose();assert.equal(geometryDisposals,6);assert.equal(materialDisposals,6);
console.log({drawCalls:6,triangles,bounds,checks:'Open portal, solid piers, finite geometry, bounds and resource disposal passed'});
